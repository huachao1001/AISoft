// AiPy 的基础类型。
//
// 刻意只有这么多：语言运行时需要的公共类型是「不透明宿主指针」与
// 「空值语义」，不需要矩形、颜色这些属于图形的东西。把它留成极小的
// 一个头，是「AiPy 不认识界面」这条边界的物理保证。
#pragma once

namespace aipy {

// 宿主对象的不透明句柄。
//
// Value 会存宿主对象（PyUI 用它装 View*，命令行宿主可能装别的）。
// AiPy 不知道它指向什么、也不解引用它——只知道「这是个宿主给自己的
// 东西，原样带回去就行」。用 void* 而不是模板参数，是因为
// Value 必须保持 16 字节、不能因为宿主类型不同而变成另一个类型。
using Host = void*;

}  // namespace aipy
